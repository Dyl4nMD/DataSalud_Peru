SELECT
    TABLE_NAME,
    COLUMN_NAME,
    DATA_TYPE,
    CHARACTER_MAXIMUM_LENGTH,
    NUMERIC_PRECISION,
    NUMERIC_SCALE,
    IS_NULLABLE
FROM INFORMATION_SCHEMA.COLUMNS
WHERE TABLE_NAME LIKE '%DIABET%'
   OR TABLE_NAME LIKE '%AFILIAD%'
ORDER BY TABLE_NAME, ORDINAL_POSITION;


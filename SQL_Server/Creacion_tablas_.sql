---Creación de la tabla PRESTACIONES_TEMPORAL:
CREATE TABLE PRESTACIONES_TEMPORAL (
    FECHA_CORTE DATE NULL,
    ID_REGISTRO_REL INT NULL,
    CODIGO_ANONIMIZADO VARCHAR(64) NULL,
    DEPARTAMENTO NVARCHAR(100) NULL,
    PROVINCIA NVARCHAR(150) NULL,
    DISTRITO NVARCHAR(150) NULL,
    UBIGEO VARCHAR(6) NULL,
    NIVEL_EESS VARCHAR(1) NULL,
    CODIGO_SERV_PRESTACIONAL VARCHAR(3) NULL,
    SERVICIO_PRESTACIONAL NVARCHAR(100) NULL,
    DIAS_HOSP INT NULL,
    EDAD_DIAS INT NULL,
    FECHA_ATENCION DATE NULL,
    SEXO VARCHAR(10) NULL,
    PESO DECIMAL(5,2) NULL,
    ATE_CAPITA VARCHAR(1) NULL
);

---En DIAS_HOSP los valores NULL representan la cantidad de 0 días, para una correcta práctica haremos el cambio con 
---el siguiente query:
UPDATE PRESTACIONES_TEMPORAL
SET DIAS_HOSP = 0
WHERE DIAS_HOSP IS NULL;

---Creación de las tablas PRESTACIONES, MEDICAMENTOS, DIAGNOSTICOS, UBIGEO_2, CATALOGO_DIAGNOSTICOS_CATALOGO_MEDICAMENTOS:
CREATE TABLE UBIGEO_2 (
    UBIGEO VARCHAR(6) NOT NULL,
    DEPARTAMENTO NVARCHAR(100) NOT NULL,
    PROVINCIA NVARCHAR(150) NOT NULL,
    DISTRITO NVARCHAR(150) NOT NULL,
    CONSTRAINT PK_UBIGEO_2 PRIMARY KEY (UBIGEO)
);

CREATE TABLE CATALOGO_DIAGNOSTICOS (
    CODDIA VARCHAR(10) NOT NULL,
    C10_NOMBRE NVARCHAR(255) NOT NULL,
    CONSTRAINT PK_CATALOGO_DIAGNOSTICOS PRIMARY KEY (CODDIA)
);

CREATE TABLE CATALOGO_MEDICAMENTOS (
    COD_MEDICAMENTO VARCHAR(6) NOT NULL,
    NOMBRE_MEDICAMENTO NVARCHAR(255) NOT NULL,
    PRESENTACIÓN VARCHAR(100) NULL,
    CONCENTRACIÓN NVARCHAR(100) NULL,
    FORMA_FARMACEUTICA VARCHAR(50) NOT NULL,
    CONSTRAINT PK_CATALOGO_MEDICAMENTOS PRIMARY KEY (COD_MEDICAMENTO)
);

CREATE TABLE PRESTACIONES (
    ID INT IDENTITY(1,1) NOT NULL,
    FECHA_CORTE DATE NOT NULL,
    ID_REGISTRO_REL INT NOT NULL,
    CODIGO_ANONIMIZADO VARCHAR(64) NOT NULL,
    UBIGEO VARCHAR(6) NOT NULL,
    NIVEL_EESS VARCHAR(1) NOT NULL,
    CODIGO_SERV_PRESTACIONAL VARCHAR(3) NOT NULL,
    SERVICIO_PRESTACIONAL NVARCHAR(100) NOT NULL,
    DIAS_HOSP INT NOT NULL,
    EDAD_DIAS INT NOT NULL,
    FECHA_ATENCION DATE NOT NULL,
    SEXO VARCHAR(10) NOT NULL,
    PESO DECIMAL(4,2) NULL,
    ATE_CAPITA VARCHAR(1) NOT NULL,
    CONSTRAINT PK_PRESTACIONES PRIMARY KEY (ID),
    CONSTRAINT UQ_PRESTACIONES_ID_REGISTRO_REL UNIQUE (ID_REGISTRO_REL),
    CONSTRAINT FK_PRESTACIONES_UBIGEO FOREIGN KEY (UBIGEO) 
        REFERENCES UBIGEO_2 (UBIGEO) ON DELETE NO ACTION ON UPDATE NO ACTION
);

CREATE TABLE DIAGNOSTICOS (
    FECHA_CORTE DATE NOT NULL,
    ID_REGISTRO_REL INT NOT NULL,
    CODDIA VARCHAR(10) NOT NULL,
    TIPO_DIAGNOSTICO VARCHAR(15) NOT NULL,
    CONSTRAINT FK_DIAGNOSTICOS_PRESTACIONES FOREIGN KEY (ID_REGISTRO_REL) 
        REFERENCES PRESTACIONES (ID_REGISTRO_REL) ON DELETE NO ACTION ON UPDATE NO ACTION,
    CONSTRAINT FK_DIAGNOSTICOS_CATALOGO FOREIGN KEY (CODDIA) 
        REFERENCES CATALOGO_DIAGNOSTICOS (CODDIA) ON DELETE NO ACTION ON UPDATE NO ACTION
);

CREATE TABLE MEDICAMENTOS (
    FECHA_CORTE DATE NOT NULL,
    ID_REGISTRO_REL INT NOT NULL,
    CODDIA VARCHAR(10) NOT NULL,
    COD_MEDICAMENTO VARCHAR(10) NOT NULL,
    CANTIDAD_ENTREGADA INT NOT NULL,
    VALOR_NETO DECIMAL(10,4) NOT NULL,
    CONSTRAINT FK_MEDICAMENTOS_PRESTACIONES FOREIGN KEY (ID_REGISTRO_REL) 
        REFERENCES PRESTACIONES (ID_REGISTRO_REL) ON DELETE NO ACTION ON UPDATE NO ACTION,
    CONSTRAINT FK_MEDICAMENTOS_CATALOGO FOREIGN KEY (COD_MEDICAMENTO) 
        REFERENCES CATALOGO_MEDICAMENTOS (COD_MEDICAMENTO) ON DELETE NO ACTION ON UPDATE NO ACTION
);


---Llenar la tabla UBIGEO_2 con los datos de PRESTACIONES_TEMPORAL:
INSERT INTO UBIGEO_2 (UBIGEO, DEPARTAMENTO, PROVINCIA, DISTRITO)
SELECT DISTINCT 
    UBIGEO, 
    DEPARTAMENTO, 
    PROVINCIA, 
    DISTRITO
FROM PRESTACIONES_TEMPORAL t
WHERE NOT EXISTS (
    SELECT 1 FROM UBIGEO_2 u WHERE u.UBIGEO = t.UBIGEO
);


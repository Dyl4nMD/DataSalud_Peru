CREATE OR ALTER FUNCTION dbo.FN_CANTIDAD_DIAGNOSTICOS
(
    @ID_REGISTRO_REL INT
)
RETURNS INT
AS
BEGIN
    DECLARE @CANTIDAD INT;

    SELECT @CANTIDAD = COUNT(*)
    FROM dbo.DIAGNOSTICOS
    WHERE ID_REGISTRO_REL = @ID_REGISTRO_REL;

    RETURN @CANTIDAD;
END;
GO

----
SELECT TOP 5
    ID_REGISTRO_REL,
    COUNT(*) AS CANTIDAD_DIAGNOSTICOS
FROM dbo.DIAGNOSTICOS
GROUP BY ID_REGISTRO_REL
ORDER BY COUNT(*) DESC;


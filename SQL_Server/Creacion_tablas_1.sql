---Creando tabla temporal para importar datos
CREATE TABLE AFILIADOS_DIABETESDM_TEMP (
    ID INT IDENTITY(1,1) NOT NULL PRIMARY KEY,
    FECHA_CORTE DATE NULL,
    FECHA_AFILIADOS_SIS DATE NULL,
    CODIGO_ANONIMIZADO VARCHAR(255) NULL,
    EDAD SMALLINT NULL,
    UBIGEO VARCHAR(20) NULL,
    DEPARTAMENTO NVARCHAR(150) NULL,
    PROVINCIA NVARCHAR(150) NULL,
    DISTRITO NVARCHAR(150) NULL,
    SEXO VARCHAR(20) NULL,
    FECHA_PRIMER_DX DATE NULL,
    TIPO_DIABETES NVARCHAR(150) NULL,
    CON_DX_OBESIDAD VARCHAR(10) NULL,
    CON_DX_HIPERTENSION VARCHAR(10) NULL,
    CON_DX_SALUDMENTAL VARCHAR(10) NULL,
    CANT_ATENCIONES INT NULL,
    VALOR_NETO DECIMAL(12,2) NULL,
    CANT_ATENCIONES_HOSP INT NULL,
    VALOR_NETO_HOSP DECIMAL(12,2) NULL,
    DIAS_HOSP INT NULL
);
GO

---CREACION DE LAS TABLAS UBIGEO, AFILIADOS Y ATENCIONES_DIABETES:
---Tabla 1: UBIGEO (Catálogo maestro)
CREATE TABLE UBIGEO (
    UBIGEO CHAR(6) NOT NULL,
    DEPARTAMENTO NVARCHAR(100) NOT NULL,
    PROVINCIA NVARCHAR(150) NOT NULL,
    DISTRITO NVARCHAR(150) NOT NULL,
    CONSTRAINT PK_UBIGEO PRIMARY KEY (UBIGEO)
);
GO

---Tabla 2: AFILIADOS (Entidad principal):
CREATE TABLE AFILIADOS (
    ID INT IDENTITY(1,1) NOT NULL,
    CODIGO_ANONIMIZADO VARCHAR(64) NOT NULL,
    EDAD TINYINT NOT NULL,
    SEXO VARCHAR(10) NOT NULL,
    UBIGEO CHAR(6) NOT NULL,
    FECHA_AFILIADOS_SIS DATE NOT NULL,
    CONSTRAINT PK_AFILIADOS PRIMARY KEY (ID),
    CONSTRAINT UQ_AFILIADOS_CODIGO UNIQUE (CODIGO_ANONIMIZADO),
    CONSTRAINT FK_AFILIADOS_UBIGEO FOREIGN KEY (UBIGEO) 
        REFERENCES UBIGEO(UBIGEO) ON DELETE NO ACTION ON UPDATE NO ACTION
);
GO

---Tabla 3: ATENCIONES_DIABETES (Tabla de hechos / atenciones):
CREATE TABLE ATENCIONES_DIABETES (
    ID INT IDENTITY(1,1) NOT NULL,
    ID_AFILIADO INT NOT NULL,
    FECHA_CORTE DATE NOT NULL,
    FECHA_PRIMER_DX DATE NOT NULL,
    TIPO_DIABETES NVARCHAR(150) NOT NULL,
    CON_DX_OBESIDAD VARCHAR(2) NOT NULL,
    CON_DX_HIPERTENSION VARCHAR(2) NOT NULL,
    CON_DX_SALUDMENTAL VARCHAR(2) NOT NULL,
    CANT_ATENCIONES INT NOT NULL,
    VALOR_NETO DECIMAL(12,2) NOT NULL,
    CANT_ATENCIONES_HOSP INT NOT NULL,
    VALOR_NETO_HOSP DECIMAL(12,2) NOT NULL,
    DIAS_HOSP INT NOT NULL,
    CONSTRAINT PK_ATENCIONES_DIABETES PRIMARY KEY (ID),
    CONSTRAINT FK_ATENCIONES_AFILIADOS FOREIGN KEY (ID_AFILIADO) 
        REFERENCES AFILIADOS(ID) ON DELETE NO ACTION ON UPDATE NO ACTION
);
GO

---Migrando los datos de la tabla temporal a sus respectivas tablas relacionadas:
---Llenar la tabla UBIGEO:
INSERT INTO UBIGEO (UBIGEO, DEPARTAMENTO, PROVINCIA, DISTRITO)
SELECT 
    RIGHT('000000' + TRIM(CAST(UBIGEO AS VARCHAR(6))), 6) AS UBIGEO,
    UPPER(TRIM(DEPARTAMENTO)),
    UPPER(TRIM(PROVINCIA)),
    UPPER(TRIM(DISTRITO))
FROM AFILIADOS_DIABETESDM_TEMP
WHERE UBIGEO IS NOT NULL AND TRIM(CAST(UBIGEO AS VARCHAR(6))) <> ''
GROUP BY 
    RIGHT('000000' + TRIM(CAST(UBIGEO AS VARCHAR(6))), 6),
    UPPER(TRIM(DEPARTAMENTO)),
    UPPER(TRIM(PROVINCIA)),
    UPPER(TRIM(DISTRITO));
GO

---Llenar la tabla AFILIADOS:
INSERT INTO AFILIADOS (CODIGO_ANONIMIZADO, EDAD, SEXO, UBIGEO, FECHA_AFILIADOS_SIS)
SELECT 
    TRIM(CODIGO_ANONIMIZADO),
    CAST(EDAD AS TINYINT),
    TRIM(SEXO),
    RIGHT('000000' + TRIM(CAST(UBIGEO AS VARCHAR(6))), 6),
    MAX(FECHA_AFILIADOS_SIS)
FROM AFILIADOS_DIABETESDM_TEMP
WHERE CODIGO_ANONIMIZADO IS NOT NULL
GROUP BY 
    TRIM(CODIGO_ANONIMIZADO),
    CAST(EDAD AS TINYINT),
    TRIM(SEXO),
    RIGHT('000000' + TRIM(CAST(UBIGEO AS VARCHAR(6))), 6);
GO

---Llenar la tabla ATENCIONES_DIABETES:
INSERT INTO ATENCIONES_DIABETES (
    ID_AFILIADO, FECHA_CORTE, FECHA_PRIMER_DX, TIPO_DIABETES, 
    CON_DX_OBESIDAD, CON_DX_HIPERTENSION, CON_DX_SALUDMENTAL, 
    CANT_ATENCIONES, VALOR_NETO, CANT_ATENCIONES_HOSP, VALOR_NETO_HOSP, DIAS_HOSP
)
SELECT 
    a.ID AS ID_AFILIADO,
    t.FECHA_CORTE,
    t.FECHA_PRIMER_DX,
    TRIM(t.TIPO_DIABETES),
    TRIM(t.CON_DX_OBESIDAD),
    TRIM(t.CON_DX_HIPERTENSION),
    TRIM(t.CON_DX_SALUDMENTAL),
    CAST(t.CANT_ATENCIONES AS INT),
    CAST(t.VALOR_NETO AS DECIMAL(12,2)),
    CAST(t.CANT_ATENCIONES_HOSP AS INT),
    CAST(t.VALOR_NETO_HOSP AS DECIMAL(12,2)),
    CAST(t.DIAS_HOSP AS INT)
FROM AFILIADOS_DIABETESDM_TEMP t
INNER JOIN AFILIADOS a 
    ON TRIM(t.CODIGO_ANONIMIZADO) = a.CODIGO_ANONIMIZADO;
GO

---Ahora eliminamos la tabla temporal:
DROP TABLE AFILIADOS_DIABETESDM_TEMP;
GO


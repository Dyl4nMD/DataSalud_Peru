USE DIRESA_PERU;
GO

CREATE TABLE dbo.LOG_AUDITORIA
(
    ID_LOG INT IDENTITY(1,1) PRIMARY KEY,
    FECHA_HORA DATETIME2 NOT NULL DEFAULT SYSDATETIME(),
    USUARIO NVARCHAR(128) NOT NULL DEFAULT SUSER_SNAME(),
    TABLA_AFECTADA VARCHAR(100) NOT NULL,
    OPERACION VARCHAR(20) NOT NULL,
    ID_REGISTRO VARCHAR(100) NULL,
    DESCRIPCION NVARCHAR(500) NULL
);
GO



---- Creamos el trigger de auditoría para nuevas prestaciones

GO
CREATE OR ALTER TRIGGER dbo.TRG_AUDITORIA_PRESTACIONES
ON dbo.PRESTACIONES
AFTER INSERT
AS
BEGIN
    SET NOCOUNT ON;

    INSERT INTO dbo.LOG_AUDITORIA
    (
        FECHA_HORA,
        USUARIO,
        TABLA_AFECTADA,
        OPERACION,
        ID_REGISTRO,
        DESCRIPCION
    )
    SELECT
        GETDATE(),
        SUSER_SNAME(),
        'PRESTACIONES',
        'INSERT',
        CAST(i.ID_REGISTRO_REL AS VARCHAR(100)),
        'Registro de nueva prestacion'
    FROM inserted i;
END;
GO



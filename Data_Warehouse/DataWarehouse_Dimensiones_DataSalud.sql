SELECT
    CODIGO_ANONIMIZADO,
    STRING_AGG(CAST(SEXO AS VARCHAR(20)), ', ') AS ValoresSexo,
    COUNT(*) AS CantidadRegistros
FROM (
    SELECT DISTINCT
        CODIGO_ANONIMIZADO,
        SEXO
    FROM DIRESA_PERU.dbo.PRESTACIONES
    WHERE CODIGO_SERV_PRESTACIONAL <> '001'
) X
GROUP BY CODIGO_ANONIMIZADO
HAVING COUNT(*) > 1;

    SELECT
        SEXO,
        COUNT(*) AS Cantidad
    FROM DIRESA_PERU.dbo.PRESTACIONES
    WHERE CODIGO_SERV_PRESTACIONAL <> '001'

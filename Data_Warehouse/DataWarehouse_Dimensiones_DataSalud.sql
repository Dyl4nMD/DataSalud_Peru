INSERT INTO dbo.DimRecienNacido (
    CodigoAnonimizado,
    Sexo
)
SELECT
    CODIGO_ANONIMIZADO,
    CASE
        WHEN COUNT(DISTINCT SEXO) = 1 THEN MAX(SEXO)
        ELSE 'NO DETERMINADO'
    END
FROM DIRESA_PERU.dbo.PRESTACIONES
WHERE CODIGO_SERV_PRESTACIONAL <> '001'
GROUP BY CODIGO_ANONIMIZADO;
GO


